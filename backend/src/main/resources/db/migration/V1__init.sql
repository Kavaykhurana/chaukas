-- Chaukas schema. Portable between PostgreSQL (prod) and H2 in PostgreSQL mode (dev/test).

CREATE TABLE app_user (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(190) NOT NULL UNIQUE,
    password_hash  VARCHAR(100) NOT NULL,
    name           VARCHAR(120) NOT NULL,
    preferred_lang VARCHAR(2)   NOT NULL DEFAULT 'en',
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

-- A ward (e.g. a parent) links to a guardian (e.g. their son or daughter) through a one-time invite code.
CREATE TABLE guardian_link (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ward_id      BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    guardian_id  BIGINT REFERENCES app_user(id) ON DELETE CASCADE,
    invite_code  VARCHAR(16) NOT NULL UNIQUE,
    status       VARCHAR(10) NOT NULL,           -- PENDING | ACTIVE
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_guardian_link_ward ON guardian_link(ward_id);
CREATE INDEX idx_guardian_link_guardian ON guardian_link(guardian_id);

-- Every verdict is logged. Only a hash of the content is kept, never the message itself.
CREATE TABLE check_record (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    input_kind       VARCHAR(12) NOT NULL,        -- TEXT | IMAGE | TEXT_IMAGE
    content_hash     VARCHAR(64) NOT NULL,
    risk             VARCHAR(8)  NOT NULL,
    scam_type        VARCHAR(24) NOT NULL,
    score            INT NOT NULL,
    ai_used          BOOLEAN NOT NULL,
    lang             VARCHAR(2) NOT NULL,
    identifiers_json TEXT NOT NULL,               -- urls / domains / upi ids / phones found
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_check_user ON check_record(user_id, created_at);
CREATE INDEX idx_check_hash ON check_record(content_hash);

-- Community scam-intel: identifiers people reported. Grown by users, never pre-seeded in prod.
CREATE TABLE scam_intel (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         VARCHAR(8)   NOT NULL,           -- UPI | PHONE | DOMAIN
    value        VARCHAR(190) NOT NULL,
    report_count INT NOT NULL,
    confirmed    BOOLEAN NOT NULL,                -- true once reported from a filed golden-hour incident
    first_seen   TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_scam_intel UNIQUE (kind, value)
);

CREATE TABLE incident (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    amount      DECIMAL(14,2),
    utr         VARCHAR(20),
    payee_upi   VARCHAR(190),
    payee_phone VARCHAR(20),
    bank        VARCHAR(60),
    paid_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    narrative   TEXT,
    lang        VARCHAR(2) NOT NULL,
    status      VARCHAR(10) NOT NULL,             -- OPEN | REPORTED
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    reported_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_incident_user ON incident(user_id, created_at);

CREATE TABLE guardian_alert (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guardian_id   BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    ward_id       BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    ward_name     VARCHAR(120) NOT NULL,
    check_id      BIGINT REFERENCES check_record(id) ON DELETE SET NULL,
    scam_type     VARCHAR(24) NOT NULL,
    message       TEXT NOT NULL,
    read_flag     BOOLEAN NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_alert_guardian ON guardian_alert(guardian_id, read_flag, created_at);
